import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../../../');
  final ndk = Platform.environment['RAFT_ADPF_NDK'];
  if (ndk == null) {
    throw ArgumentError('Set RAFT_ADPF_NDK to an Android NDK 30 directory.');
  }
  final host = Platform.isMacOS ? 'darwin-x86_64' : 'linux-x86_64';
  final sysroot = '$ndk/toolchains/llvm/prebuilt/$host/sysroot';
  for (final entry in {
    'performance_hint': {
      'APerformanceHint_getManager',
      'APerformanceHint_createSession',
      'APerformanceHint_closeSession',
      'APerformanceHint_updateTargetWorkDuration',
      'APerformanceHint_reportActualWorkDuration',
      'APerformanceHint_notifyWorkloadReset',
    },
    'unistd': {'gettid'},
  }.entries) {
    final header = File.fromUri(
      root.resolve('third_party/android/${entry.key}.h'),
    ).readAsStringSync();
    final license = header.substring(0, header.indexOf('*/') + 2);
    await FfiGenerator(
      input: Input(
        entryPoints: [root.resolve('third_party/android/${entry.key}.h')],
        compilerOptions: [
          '--target=aarch64-linux-android37',
          '-resource-dir=$ndk/toolchains/llvm/prebuilt/$host/lib/clang/21',
          '--sysroot=$sysroot',
          '-I$sysroot/usr/include/aarch64-linux-android',
        ],
      ),
      visitors: [
        Visitor(
          func: (node) {
            node.isIncluded = entry.value.contains(node.originalName);
            // FFIgen 23's visitor is the equivalent of Functions.recordUse.
            node.recordUse = node.isIncluded;
          },
        ),
      ],
      output: Output(
        dart: DartOutput(
          path: root.resolve('lib/src/third_party/${entry.key}.g.dart'),
        ),
        style: const NativeExternalBindings(),
        // ignore: experimental_member_use
        recordUseMapping: root.resolve(
          'lib/src/third_party/${entry.key}.record_use_mapping.g.dart',
        ),
        preamble:
            '$license\n// Generated by package:ffigen. Do not edit manually.\n// Regenerate: RAFT_ADPF_NDK=<ndk30> dart run tool/ffigen.dart\n// ignore_for_file: type=lint, unused_import, experimental_member_use, doc_directive_unknown\n',
      ),
    ).generate();
  }
}
